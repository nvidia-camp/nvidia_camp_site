CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS report_categories (
    category_id INTEGER PRIMARY KEY CHECK (category_id >= 1),
    code TEXT NOT NULL UNIQUE CHECK (code IN ('EXPERIMENT','DAILY_WORK','RESEARCH_PLAN','DATA_PROCESSING','PROMPT','MEETING')),
    name TEXT NOT NULL CHECK (char_length(btrim(name)) >= 1),
    description TEXT
);
CREATE TABLE IF NOT EXISTS reports (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER NOT NULL REFERENCES report_categories(category_id) ON DELETE RESTRICT,
    overview VARCHAR(1000) NOT NULL CHECK (char_length(btrim(overview)) BETWEEN 10 AND 1000),
    index_status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (index_status IN ('pending','ready','failed')),
    revision INTEGER NOT NULL DEFAULT 1 CHECK (revision >= 1)
);
CREATE TABLE IF NOT EXISTS report_embeddings (
    report_id BIGINT PRIMARY KEY REFERENCES reports(report_id) ON DELETE CASCADE,
    embedding vector(384) NOT NULL,
    model_name TEXT NOT NULL CHECK (char_length(btrim(model_name)) >= 1),
    overview_hash CHAR(64) NOT NULL CHECK (overview_hash ~ '^[0-9a-f]{64}$'),
    indexed_revision INTEGER NOT NULL CHECK (indexed_revision >= 1),
    indexed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS experiment_reports (
    report_id BIGINT PRIMARY KEY REFERENCES reports(report_id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 200),
    content TEXT NOT NULL CHECK (char_length(btrim(content)) BETWEEN 1 AND 20000),
    author VARCHAR(100) NOT NULL CHECK (char_length(btrim(author)) BETWEEN 1 AND 100),
    create_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    update_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    experiment_date DATE NOT NULL,
    hypothesis TEXT NOT NULL CHECK (char_length(btrim(hypothesis)) >= 1),
    result_summary TEXT NOT NULL CHECK (char_length(btrim(result_summary)) >= 1),
    CONSTRAINT experiment_reports_time_check CHECK (update_at >= create_at)
);
CREATE TABLE IF NOT EXISTS daily_work_reports (
    report_id BIGINT PRIMARY KEY REFERENCES reports(report_id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 200),
    content TEXT NOT NULL CHECK (char_length(btrim(content)) BETWEEN 1 AND 20000),
    author VARCHAR(100) NOT NULL CHECK (char_length(btrim(author)) BETWEEN 1 AND 100),
    create_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    update_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    work_date DATE NOT NULL,
    progress TEXT NOT NULL CHECK (char_length(btrim(progress)) >= 1),
    blockers TEXT NOT NULL DEFAULT '',
    CONSTRAINT daily_work_reports_time_check CHECK (update_at >= create_at)
);
CREATE TABLE IF NOT EXISTS research_plans (
    report_id BIGINT PRIMARY KEY REFERENCES reports(report_id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 200),
    content TEXT NOT NULL CHECK (char_length(btrim(content)) BETWEEN 1 AND 20000),
    author VARCHAR(100) NOT NULL CHECK (char_length(btrim(author)) BETWEEN 1 AND 100),
    create_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    update_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    research_goal TEXT NOT NULL CHECK (char_length(btrim(research_goal)) >= 1),
    methodology TEXT NOT NULL CHECK (char_length(btrim(methodology)) >= 1),
    target_date DATE NOT NULL,
    CONSTRAINT research_plans_time_check CHECK (update_at >= create_at)
);
CREATE TABLE IF NOT EXISTS data_processing_reports (
    report_id BIGINT PRIMARY KEY REFERENCES reports(report_id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 200),
    content TEXT NOT NULL CHECK (char_length(btrim(content)) BETWEEN 1 AND 20000),
    author VARCHAR(100) NOT NULL CHECK (char_length(btrim(author)) BETWEEN 1 AND 100),
    create_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    update_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    dataset_name TEXT NOT NULL CHECK (char_length(btrim(dataset_name)) >= 1),
    processing_steps TEXT NOT NULL CHECK (char_length(btrim(processing_steps)) >= 1),
    quality_notes TEXT NOT NULL DEFAULT '',
    CONSTRAINT data_processing_reports_time_check CHECK (update_at >= create_at)
);
CREATE TABLE IF NOT EXISTS prompt_reports (
    report_id BIGINT PRIMARY KEY REFERENCES reports(report_id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 200),
    content TEXT NOT NULL CHECK (char_length(btrim(content)) BETWEEN 1 AND 20000),
    author VARCHAR(100) NOT NULL CHECK (char_length(btrim(author)) BETWEEN 1 AND 100),
    create_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    update_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    purpose TEXT NOT NULL CHECK (char_length(btrim(purpose)) >= 1),
    active_version_no INTEGER NOT NULL DEFAULT 1 CHECK (active_version_no >= 1),
    CONSTRAINT prompt_reports_time_check CHECK (update_at >= create_at)
);
CREATE TABLE IF NOT EXISTS meeting_minutes (
    report_id BIGINT PRIMARY KEY REFERENCES reports(report_id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 200),
    content TEXT NOT NULL CHECK (char_length(btrim(content)) BETWEEN 1 AND 20000),
    author VARCHAR(100) NOT NULL CHECK (char_length(btrim(author)) BETWEEN 1 AND 100),
    create_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    update_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    meeting_at TIMESTAMPTZ NOT NULL,
    attendees TEXT NOT NULL CHECK (char_length(btrim(attendees)) >= 1),
    decisions TEXT NOT NULL CHECK (char_length(btrim(decisions)) >= 1),
    CONSTRAINT meeting_minutes_time_check CHECK (update_at >= create_at)
);
CREATE TABLE IF NOT EXISTS prompt_versions (
    prompt_version_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES prompt_reports(report_id) ON DELETE CASCADE,
    version_no INTEGER NOT NULL CHECK (version_no >= 1),
    prompt_text TEXT NOT NULL CHECK (char_length(btrim(prompt_text)) BETWEEN 1 AND 20000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_prompt_versions_report_no UNIQUE (report_id, version_no)
);
CREATE INDEX IF NOT EXISTS idx_reports_category ON reports(category_id);
CREATE INDEX IF NOT EXISTS idx_reports_ready ON reports(index_status) WHERE index_status='ready';
CREATE INDEX IF NOT EXISTS idx_prompt_versions_report ON prompt_versions(report_id, version_no);
-- 180개 실습 데이터는 Exact Search로 충분: HNSW 인덱스는 고급 선택 과제입니다.

-- 인덱싱/조회에서 쓰는 VIEW는 물리 테이블이 아닙니다(ERD 10개 유지).
-- 제목·본문이 6개 종류별 상세 테이블에만 있으므로, 동일한 조회 계약을 제공합니다.
CREATE OR REPLACE VIEW report_read_view AS
SELECT r.report_id,r.category_id,c.code AS category_code,
       d.title,d.content,d.author,d.create_at,d.update_at,
       r.overview,r.index_status,r.revision
FROM reports r
JOIN report_categories c ON c.category_id=r.category_id AND c.code='EXPERIMENT'
JOIN experiment_reports d ON d.report_id=r.report_id
UNION ALL
SELECT r.report_id,r.category_id,c.code AS category_code,
       d.title,d.content,d.author,d.create_at,d.update_at,
       r.overview,r.index_status,r.revision
FROM reports r
JOIN report_categories c ON c.category_id=r.category_id AND c.code='DAILY_WORK'
JOIN daily_work_reports d ON d.report_id=r.report_id
UNION ALL
SELECT r.report_id,r.category_id,c.code AS category_code,
       d.title,d.content,d.author,d.create_at,d.update_at,
       r.overview,r.index_status,r.revision
FROM reports r
JOIN report_categories c ON c.category_id=r.category_id AND c.code='RESEARCH_PLAN'
JOIN research_plans d ON d.report_id=r.report_id
UNION ALL
SELECT r.report_id,r.category_id,c.code AS category_code,
       d.title,d.content,d.author,d.create_at,d.update_at,
       r.overview,r.index_status,r.revision
FROM reports r
JOIN report_categories c ON c.category_id=r.category_id AND c.code='DATA_PROCESSING'
JOIN data_processing_reports d ON d.report_id=r.report_id
UNION ALL
SELECT r.report_id,r.category_id,c.code AS category_code,
       d.title,d.content,d.author,d.create_at,d.update_at,
       r.overview,r.index_status,r.revision
FROM reports r
JOIN report_categories c ON c.category_id=r.category_id AND c.code='PROMPT'
JOIN prompt_reports d ON d.report_id=r.report_id
UNION ALL
SELECT r.report_id,r.category_id,c.code AS category_code,
       d.title,d.content,d.author,d.create_at,d.update_at,
       r.overview,r.index_status,r.revision
FROM reports r
JOIN report_categories c ON c.category_id=r.category_id AND c.code='MEETING'
JOIN meeting_minutes d ON d.report_id=r.report_id;
